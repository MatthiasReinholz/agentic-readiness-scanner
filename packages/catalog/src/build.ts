/**
 * Builds the catalog package:
 *   - src/generated/catalog.ts   typed constant for TypeScript consumers (bundles into workers)
 *   - dist/catalog.json          for non-JavaScript consumers (the WordPress plugin)
 *   - dist/schema/*.json         JSON Schema for the catalog and the scan result
 *
 * `--check` validates without writing anything.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { z } from 'zod';

import { loadCatalogFromDisk, CatalogLoadError } from './load.js';
import { ScanResultSchema } from './result.js';
import { CatalogSchema } from './schema.js';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

try {
  const catalog = loadCatalogFromDisk(packageRoot);
  console.log(
    `Catalog ${catalog.version} (scoring ${catalog.scoring_version}): ${catalog.checks.length} checks in ${catalog.groups.length} groups, ${catalog.levels.length} levels, ${catalog.profiles.length} profiles.`,
  );
  if (!checkOnly) {
    const generatedDir = join(packageRoot, 'src', 'generated');
    const distDir = join(packageRoot, 'dist');
    const schemaDir = join(distDir, 'schema');
    mkdirSync(generatedDir, { recursive: true });
    mkdirSync(schemaDir, { recursive: true });

    const json = JSON.stringify(catalog, null, 2);
    writeFileSync(
      join(generatedDir, 'catalog.ts'),
      `// Generated by src/build.ts from data/ and fixes/. Do not edit.\nimport type { Catalog } from '../schema.js';\n\nexport const catalog: Catalog = ${json} as const;\n`,
    );
    writeFileSync(join(distDir, 'catalog.json'), `${json}\n`);
    writeFileSync(
      join(schemaDir, 'catalog.schema.json'),
      `${JSON.stringify(z.toJSONSchema(CatalogSchema, { target: 'draft-2020-12' }), null, 2)}\n`,
    );
    writeFileSync(
      join(schemaDir, 'scan-result.schema.json'),
      `${JSON.stringify(z.toJSONSchema(ScanResultSchema, { target: 'draft-2020-12' }), null, 2)}\n`,
    );
    console.log('Wrote src/generated/catalog.ts, dist/catalog.json and dist/schema/*.json.');
  }
} catch (error) {
  if (error instanceof CatalogLoadError) {
    console.error(error.message);
    process.exit(1);
  }
  throw error;
}
