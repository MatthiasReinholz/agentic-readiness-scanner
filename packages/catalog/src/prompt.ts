/**
 * Composes the prompt a merchant pastes into a coding agent for one finding.
 *
 * The catalog's per-check `agent_prompt` states the task. This wrapper adds what the
 * agent needs around it: where the request comes from, what was observed, the specs the
 * check is grounded in, and how to work (investigate first, prefer a durable fix over a
 * patch, verify). Kept in one place so every surface (HTML, Markdown, MCP) hands agents
 * the same brief.
 */
import type { CheckDefinition, Verdict } from './schema.js';

export interface AgentPromptContext {
  /** Canonical target URL that was scanned. */
  targetUrl?: string;
  /** ISO timestamp of the scan. */
  scannedAt?: string;
  /** Detected platform, e.g. woocommerce. */
  platform?: string;
  /** The verdict the check produced. */
  verdict?: Verdict;
  /** The one-line message that came with the verdict. */
  message?: string;
  /** Link to the full report, when hosted. */
  reportUrl?: string;
  /** Name and URL of the scanner, for attribution. */
  scannerName?: string;
  scannerUrl?: string;
}

const DEFAULT_SCANNER_NAME = 'Agentic Readiness Scanner';
const DEFAULT_SCANNER_URL = 'https://github.com/MatthiasReinholz/agentic-readiness-scanner';

/** The working rules every composed prompt ends with. Exported so docs can quote them. */
export const AGENT_WORKING_RULES: readonly string[] = [
  'Investigate before you change anything. Read the relevant templates, plugin or app settings, server configuration and data model, and reproduce the finding yourself (fetch the live URLs the way a crawler would, with no cookies and no JavaScript). If the finding no longer holds, say so and stop.',
  'Fix the cause where it lives. Prefer the platform feature, setting or data field that is meant for this over a hard-coded patch, a one-off template hack or a duplicated value that will drift. The result must survive theme, plugin and platform updates.',
  'Keep the change small, reversible and in the conventions of this codebase. Do not disable security controls, do not loosen bot rules beyond what the task needs, and do not touch unrelated behaviour.',
  'Verify against the specification linked above and against the real pages, not only in a local preview. Then re-run the scan to confirm the check passes without regressing others.',
  'Report what you changed, where, and anything you could not resolve or that needs a decision from the store owner.',
];

function verdictSentence(verdict: Verdict | undefined, title: string): string {
  switch (verdict) {
    case 'fail':
      return `the check "${title}" failed`;
    case 'warn':
      return `the check "${title}" passed only partially`;
    case 'pass':
      return `the check "${title}" passed; this prompt is provided for reference`;
    case 'skip':
      return `the check "${title}" could not be evaluated`;
    default:
      return `the check "${title}" needs attention`;
  }
}

/** Builds the full brief for one check. Plain Markdown, safe to paste anywhere. */
export function composeAgentPrompt(
  check: Pick<CheckDefinition, 'id' | 'title' | 'question' | 'method' | 'spec' | 'fix'>,
  context: AgentPromptContext = {},
): string {
  const scannerName = context.scannerName ?? DEFAULT_SCANNER_NAME;
  const scannerUrl = context.scannerUrl ?? DEFAULT_SCANNER_URL;
  const where = context.targetUrl ? ` of ${context.targetUrl}` : '';
  const when = context.scannedAt ? ` on ${context.scannedAt.slice(0, 10)}` : '';
  const platform =
    context.platform && context.platform !== 'unknown'
      ? ` (detected platform: ${context.platform})`
      : '';
  const lines: string[] = [];
  lines.push(`# Fix request: ${check.id} ${check.title}`);
  lines.push('');
  lines.push('## Why you are receiving this');
  lines.push('');
  lines.push(
    `This brief was generated by the ${scannerName} (${scannerUrl}), an open-source tool that checks whether AI shopping agents and crawlers can find, read, trust and buy from a web store using public signals only. A scan${where}${when}${platform} found that ${verdictSentence(context.verdict, check.title)}.${context.message ? ` Observation: ${context.message}` : ''}${context.reportUrl ? ` Full report: ${context.reportUrl}` : ''}`,
  );
  lines.push('');
  lines.push('## What the check looks for');
  lines.push('');
  lines.push(check.question);
  lines.push('');
  lines.push(`How it is evaluated: ${check.method}`);
  lines.push('');
  lines.push('Specifications this check is grounded in:');
  lines.push('');
  for (const ref of check.spec) lines.push(`- ${ref.title}: ${ref.url}`);
  lines.push('');
  lines.push('## Your task');
  lines.push('');
  lines.push(check.fix.agent_prompt);
  lines.push('');
  lines.push('## How to work');
  lines.push('');
  AGENT_WORKING_RULES.forEach((rule, index) => lines.push(`${index + 1}. ${rule}`));
  return lines.join('\n');
}
