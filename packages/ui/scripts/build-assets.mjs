// Generates src/generated/: the compiled, minified Tailwind stylesheet as a TypeScript
// string constant, and the lucide icons the templates use as SVG strings. Both are build
// outputs (gitignored); the package's tsc build compiles them with the rest of src/.
//
// The stylesheet is a string on purpose: the HTML report must stay a single self-contained
// file (the CLI writes it to disk, the hosted app inlines it), so there is no stylesheet
// URL to link.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const outDir = join(packageRoot, 'src', 'generated');
mkdirSync(outDir, { recursive: true });

// Stylesheet
const tailwindCli = require.resolve('tailwindcss/lib/cli.js');
const cssFile = join(outDir, 'theme.css');
execFileSync(
  process.execPath,
  [tailwindCli, '-c', 'tailwind.config.ts', '-i', 'src/theme.css', '-o', cssFile, '--minify'],
  {
    cwd: packageRoot,
    stdio: ['ignore', 'ignore', 'inherit'],
    env: { ...process.env, BROWSERSLIST_IGNORE_OLD_DATA: '1' },
  },
);
const css = readFileSync(cssFile, 'utf8').trim();
writeFileSync(
  join(outDir, 'theme-css.ts'),
  `// Generated by scripts/build-assets.mjs from src/theme.css and tailwind.config.ts. Do not edit.\n` +
    `export const THEME_CSS = ${JSON.stringify(css)};\n`,
);

// Icons. Add a name here and use icon('name') in a template; nothing else to wire.
const ICONS = [
  'arrow-left',
  'bell',
  'check',
  'chevron-down',
  'chevron-right',
  'circle-alert',
  'circle-check',
  'copy',
  'external-link',
  'info',
  'minus',
  'moon',
  'sun',
  'triangle-alert',
  'x',
];
const lucideDir = dirname(require.resolve('lucide-static/package.json'));
const lucideVersion = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8')).version;
const entries = ICONS.map((name) => {
  const file = readFileSync(join(lucideDir, 'icons', `${name}.svg`), 'utf8');
  // The file opens with a licence comment; the element itself starts at <svg.
  const svg = file
    .slice(file.indexOf('<svg'))
    .replace(/\s+width="24"\s+height="24"/, '')
    .replace(/\s+class="[^"]*"/, '')
    .replace(/\s+/g, ' ')
    .replace(/ >/g, '>')
    .replace(/ \/>/g, '/>')
    .trim();
  return `  '${name}': ${JSON.stringify(svg)},`;
});
writeFileSync(
  join(outDir, 'icons.ts'),
  `// Generated by scripts/build-assets.mjs from lucide-static ${lucideVersion} (ISC licence). Do not edit.\n` +
    `export const ICON_SVG = {\n${entries.join('\n')}\n} as const;\n\n` +
    `export type IconName = keyof typeof ICON_SVG;\n`,
);

console.log(`ui: ${(css.length / 1024).toFixed(1)} kB of CSS, ${ICONS.length} icons`);
